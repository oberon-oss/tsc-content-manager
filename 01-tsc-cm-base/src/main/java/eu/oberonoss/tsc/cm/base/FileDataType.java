package eu.oberonoss.tsc.cm.base;

/**
 * Enumerates the supported file data types.
 *
 * @author TigerLilly64
 * @since 1.0.0
 */
public enum FileDataType {
    /**
     * Binary file containing SERZ formatted data
     *
     * @since 1.0.0
     */
    SERZ_BINARY,
    /**
     * XML file containing SERZ formatted data
     *
     * @since 1.0.0
     */
    SERZ_XML
}
